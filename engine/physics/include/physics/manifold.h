#pragma once
#include "physics/shapes.h"

/**
 * @file manifold.h
 * @brief Contact manifold generation: narrowphase results reduced to stable
 *        contact points (Layer 3 — Subsystems).
 *
 * A single normal + penetration depth (physics/collision.h's `Contact`) is
 * enough to know *that* two shapes overlap, but not enough to keep a box
 * resting on a face from rocking — that needs the actual set of contact
 * points (up to 4, one per corner of the contact patch). See
 * docs/phases/05-physics.md (Milestone 3).
 */
namespace ge::physics {

/** @brief One contact point within a Manifold. */
struct ManifoldPoint {
    vec3 point{};        ///< World-space contact position (midpoint between the two surfaces).
    f32  penetration = 0.0f; ///< Overlap depth along Manifold::normal at this point; always >= 0.
};

/**
 * @brief Up to 4 contact points sharing one separating axis.
 *
 * `normal` follows the same "first shape argument -> second" convention as
 * `Contact` (physics/collision.h).
 */
struct Manifold {
    static constexpr u32 kMaxPoints = 4;

    bool  valid = false;
    vec3  normal{0, 1, 0}; // a -> b
    u32   count = 0;
    ManifoldPoint points[kMaxPoints]{};
};

/** @brief Single-point manifold from a sphere-sphere overlap. */
Manifold manifold_sphere_sphere(const Sphere& a, const Sphere& b);

/** @brief Single-point manifold from a sphere-box overlap. */
Manifold manifold_sphere_box(const Sphere& s, const Box& b);

/**
 * @brief Single-point manifold from a capsule-box overlap.
 *
 * A capsule is the Minkowski sum of its core segment and a sphere, so this
 * reduces to a sphere-box-style contact at the segment's closest point.
 */
Manifold manifold_capsule_box(const Capsule& c, const Box& b);

/**
 * @brief Manifold from a box-box overlap.
 *
 * Face contacts (the winning SAT axis is a face normal of either box) are
 * generated by clipping the incident box's face against the reference
 * face's 4 side planes (Sutherland-Hodgman), yielding up to 4 points. Edge
 * contacts (the winning axis is one of the 9 edge cross-products) reduce to
 * a single point: the midpoint of the closest points between the two
 * witness edges.
 */
Manifold manifold_box_box(const Box& a, const Box& b);

} // namespace ge::physics
